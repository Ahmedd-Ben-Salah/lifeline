"""
Build the planet textures used by the 3D views and the terrain maps.

Inputs (public-domain / open sources, downloaded once into SRC):
  mars color   : Viking-based global colour mosaic (KyleGough/solar-system, from solarsystemscope / NASA),
                 2000x1000, longitudes 0..360°E
  mars relief  : MOLA-derived elevation map, 2048x1024, 0..360°E
  earth        : NASA Blue Marble (day), NASA Black Marble (night), ocean mask, topology (three-globe examples)
  stars        : NASA SVS Tycho star map (celestial sphere)
  moons        : NASA 3D Resources — Phobos, Deimos, Moon

Outputs (public/textures and lib/engine/data):
  mars-color-4k.jpg / mars-color-2k.jpg  colour, re-centred to −180..180°E, sharpened, relief-enhanced
  mars-normal-4k.jpg                     tangent-space normal map computed from MOLA slopes
  mars-relief-4k.jpg                     shaded-relief map for the 2D map views (colour × hillshade)
  earth-*.jpg                            Earth layers (+ normal map from topology)
  stars.jpg, sun.jpg, moon.jpg, phobos.jpg, deimos.jpg
  lib/engine/data/mola.ts                1°×1° elevation grid (metres) for the rover router

Run:  python3 scripts/build_textures.py <src_dir>
"""
import base64, os, sys
import numpy as np
from PIL import Image, ImageFilter, ImageEnhance

SRC = sys.argv[1] if len(sys.argv) > 1 else 'tex'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'textures')
os.makedirs(OUT, exist_ok=True)
Image.MAX_IMAGE_PIXELS = None

def src(name): return Image.open(os.path.join(SRC, name))
def save(im, name, q=86):
    p = os.path.join(OUT, name)
    im.convert('RGB').save(p, quality=q, optimize=True, progressive=True)
    print(f'{name:28s} {im.size}  {os.path.getsize(p)//1024} KB')

def roll_half(a):
    """0..360°E maps -> −180..180°E (standard equirectangular, left edge = 180°W)."""
    return np.roll(a, a.shape[1] // 2, axis=1)

# ---------------- MARS ----------------
MOLA_MIN, MOLA_MAX = -8200.0, 21229.0   # metres, MOLA global range (Hellas floor .. Olympus Mons)

relief8 = np.asarray(src('kg-mars-bump.jpg').convert('L'), dtype=np.float32)
relief8 = roll_half(relief8)
elev = MOLA_MIN + relief8 / 255.0 * (MOLA_MAX - MOLA_MIN)   # metres (approximate, 8-bit)

def hillshade(z, az=315, alt=38, z_scale=1.0):
    gy, gx = np.gradient(z)
    slope = np.pi / 2 - np.arctan(z_scale * np.hypot(gx, gy))
    aspect = np.arctan2(-gx, gy)
    az, alt = np.radians(az), np.radians(alt)
    hs = np.sin(alt) * np.sin(slope) + np.cos(alt) * np.cos(slope) * np.cos(az - aspect)
    return np.clip(hs, 0, 1)

def resize_f(a, size):
    return np.asarray(Image.fromarray(a.astype(np.float32), mode='F').resize(size, Image.BICUBIC))

W4, H4 = 4096, 2048
elev4 = resize_f(elev, (W4, H4))
# metres per pixel at 4k ≈ 2π·3389.5 km / 4096 ≈ 5.2 km; exaggerate relief for readability
hs4 = hillshade(elev4 / 5200.0, z_scale=6.0)

color = src('kg-mars.jpg').convert('RGB')
c = roll_half(np.asarray(color, dtype=np.float32))
color4 = Image.fromarray(c.astype(np.uint8)).resize((W4, H4), Image.LANCZOS)
color4 = color4.filter(ImageFilter.UnsharpMask(radius=2.2, percent=70, threshold=2))
ca = np.asarray(color4, dtype=np.float32) / 255.0
# subtle relief in the albedo map so craters and Valles read at close range
detail = (0.78 + 0.32 * hs4)[..., None]
mars4 = np.clip(ca * detail, 0, 1)
# gentle grade toward measured Mars colour (butterscotch, less neon orange)
mars4 = mars4 ** np.array([1.0, 1.04, 1.10])
mars4 = (mars4 * 255).astype(np.uint8)
save(Image.fromarray(mars4), 'mars-color-4k.jpg', 88)
save(Image.fromarray(mars4).resize((2048, 1024), Image.LANCZOS), 'mars-color-2k.jpg', 86)

# normal map (tangent space, +Y = north) from elevation
gy, gx = np.gradient(elev4 / 5200.0 * 7.0)
nx, ny, nz = -gx, gy, np.ones_like(gx)
n = np.sqrt(nx * nx + ny * ny + nz * nz)
nm = np.stack([(nx / n + 1) * 127.5, (ny / n + 1) * 127.5, (nz / n + 1) * 127.5], -1).astype(np.uint8)
save(Image.fromarray(nm), 'mars-normal-4k.jpg', 90)
save(Image.fromarray(nm).resize((2048, 1024), Image.LANCZOS), 'mars-normal-2k.jpg', 90)

# shaded relief for 2D maps (stronger hillshade, slight desaturation)
hs_map = hillshade(elev4 / 5200.0, z_scale=10.0)
rel = np.clip(ca * (0.55 + 0.6 * hs_map)[..., None], 0, 1)
rel = (rel * 255).astype(np.uint8)
im = ImageEnhance.Contrast(Image.fromarray(rel)).enhance(1.08)
save(im, 'mars-relief-4k.jpg', 86)

# 1°×1° elevation grid for the router (lat 89.5..-89.5, lon -179.5..179.5)
grid = resize_f(elev, (360, 180))
q = np.clip(np.round((grid - MOLA_MIN) / (MOLA_MAX - MOLA_MIN) * 65535), 0, 65535).astype('<u2')
b64 = base64.b64encode(q.tobytes()).decode()
os.makedirs(os.path.join(ROOT, 'lib', 'engine', 'data'), exist_ok=True)
with open(os.path.join(ROOT, 'lib', 'engine', 'data', 'mola.ts'), 'w') as f:
    f.write('// Generated by scripts/build_textures.py — MOLA-derived elevation, 1°x1°, 360x180, uint16 little-endian.\n')
    f.write('// Row 0 = latitude 89.5°N, column 0 = longitude 179.5°W. value/65535 maps to [MIN, MAX] metres.\n')
    f.write(f'export const MOLA_MIN = {MOLA_MIN};\nexport const MOLA_MAX = {MOLA_MAX};\n')
    f.write(f'export const MOLA_W = 360;\nexport const MOLA_H = 180;\nexport const MOLA_B64 = "{b64}";\n')
print('mola.ts written')

# ---------------- EARTH ----------------
save(src('earth-blue-marble.jpg'), 'earth-day.jpg', 88)
night = src('earth-night.jpg')
save(night, 'earth-night.jpg', 88)
save(src('earth-water.png').convert('L').resize((2048, 1024), Image.LANCZOS), 'earth-water.jpg', 90)
clouds = src('kg-earth-clouds.jpg').convert('L').resize((2048, 1024), Image.LANCZOS)
save(clouds, 'earth-clouds.jpg', 88)
topo = np.asarray(src('earth-topology.png').convert('L'), dtype=np.float32)
gy, gx = np.gradient(topo / 255.0 * 6.0)
n = np.sqrt(gx * gx + gy * gy + 1)
enm = np.stack([(-gx / n + 1) * 127.5, (gy / n + 1) * 127.5, (1 / n + 1) * 127.5], -1).astype(np.uint8)
save(Image.fromarray(enm), 'earth-normal.jpg', 90)

# ---------------- SKY, SUN, MOONS ----------------
stars = np.asarray(src('tycho.jpg').convert('RGB'), dtype=np.float32) / 255.0
stars = np.clip(stars ** 0.72 * 1.9, 0, 1)
save(Image.fromarray((stars * 255).astype(np.uint8)), 'stars.jpg', 84)
save(src('kg-sun.jpg'), 'sun.jpg', 84)
save(src('kg-moon.jpg'), 'moon.jpg', 86)
save(src('phobos.jpg'), 'phobos.jpg', 86)
save(src('deimos.jpg'), 'deimos.jpg', 86)
